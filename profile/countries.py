AU_STATE_CODES = {
    'australian capital territory': 'ACT', 'new south wales': 'NSW',
    'northern territory': 'NT', 'queensland': 'QLD', 'south australia': 'SA',
    'tasmania': 'TAS', 'victoria': 'VIC', 'western australia': 'WA',
}

STATE_CODES = {'US': US_STATE_CODES, 'AU': AU_STATE_CODES}
_STATE_CODE_SETS = {country: frozenset(codes.values()) for country, codes in STATE_CODES.items()}


def normalise_country(value: str | None) -> str | None:
    """A two letter code from either a code or a spelled out country name."""
    country = (value or '').strip()
    if country.upper() in VALID_CODES:
        return country.upper()
    return CODES_BY_NAME.get(country.lower())


def state_code(country: str | None, state: str | None) -> str | None:
    """
    The code Wise wants for a state, or ``None`` when it asks for no state.

    Only US and Australian addresses need one, and the field is free text, so
    accept either the code or the spelled out name.
    """
    resolved = normalise_country(country)
    codes = STATE_CODES.get(resolved)
    if not codes:
        return None
    value = (state or '').strip()
    code = codes.get(value.lower(), value.upper())
    return code if code in _STATE_CODE_SETS[resolved] else None
